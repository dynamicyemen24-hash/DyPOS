#!/usr/bin/env node
/**
 * DyPOS SQLite → Postgres parity generator.
 *
 * server/db/schema.js (SQLite) is the data model; server/db/schema-postgres.sql
 * is the Tier-2 target. Hand-keeping 49 tables + ~118 columns + ~129 indexes in
 * lockstep is how drift happens, so the missing objects are GENERATED from the
 * migrated SQLite schema into a marker-bounded section at the end of the file:
 *
 *   npm run parity:sync && npm run parity     (in server/)
 *
 * The section is regenerated whole (idempotent — re-running with no schema
 * drift rewrites identical bytes). Hand-written DDL above the marker is never
 * touched; the generator only ever reads it (scripts/lib/parity-sql.mjs, the
 * same reader the CI gate uses, so the gate and the generator cannot disagree
 * about what the baseline already contains).
 *
 * Emission order — every statement runs against a plain `psql -f`:
 *   1. CREATE TABLE for tables SQLite has and the baseline lacks,
 *      topologically sorted so each FK target already exists;
 *   2. ALTER TABLE ADD COLUMN for columns SQLite has and a baseline table lacks
 *      (sorted so an FK to another added column runs first);
 *   3. CREATE INDEX for indexes SQLite has and the baseline lacks.
 * FK targets are validated before writing: a target that would only exist
 * after the statement that needs it is a hard error, not a warning.
 *
 * Type mapping (the gate normalizes types away; these keep the SQL runnable):
 *   TEXT → TEXT · INTEGER → BIGINT · REAL → NUMERIC(18,6)
 *   is_/has_/allow_/track_/requires_/can_/should_ INTEGER → BOOLEAN (1/0 → TRUE/FALSE)
 *   *_at → TIMESTAMPTZ · *_date / valid_from / valid_to → DATE
 *   (datetime('now')) → now() · (date('now')) → (now() AT TIME ZONE 'UTC')::date
 *   an FK column adopts its target's Postgres type (UUID for uuid-keyed
 *   baseline tables such as products/users, TEXT for text-keyed ones).
 *
 * Run: npm run parity:sync
 * Exit: 0 written · 2 failure
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	isConstraintHead,
	matchParen,
	parsePgObjects,
	splitColDef,
	splitTopParts,
	stripLineComments,
	tableBodyOf,
} from './lib/parity-sql.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SERVER = join(HERE, '..');
const PG_PATH = join(SERVER, 'db', 'schema-postgres.sql');
const BEGIN_MARK = '-- >>> gen-pg-parity: BEGIN (generated by scripts/gen-pg-parity.mjs — do not edit) >>>';
const END_MARK = '-- <<< gen-pg-parity: END <<<';

const FK_RE = /\bREFERENCES\s+([a-z_][a-z0-9_]*)(?:\s*\(\s*([a-z_][a-z0-9_]*)\s*\))?/i;
const FLAG_RE = /^(is|has|allow|track|requires|can|should)_/i;
const DATE_NAME_RE = /_date$/;
const AT_NAME_RE = /_at$/;
const DATE_EXPLICIT = new Set(['valid_from', 'valid_to']);
const IGNORED_TABLES = new Set(['schema_version']);
const isFtsTable = (t) => t === 'products_fts' || t.startsWith('products_fts_');

const warn = (msg) => process.stderr.write(`[gen-pg-parity] ${msg}\n`);
const fail = (msg) => {
	throw new Error(msg);
};

/* ------------------------------------------------------------------ SQLite */

async function readSqliteSchema() {
	process.env.DYPOS_DB_PATH = ':memory:';
	const { db, migrate } = await import('../db/schema.js');
	migrate();
	const rows = db
		.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid")
		.all();
	const tables = rows.map((r) => {
		const clean = stripLineComments(r.sql);
		const defs = new Map();
		const tableConstraints = [];
		for (const part of splitTopParts(tableBodyOf(clean))) {
			if (isConstraintHead(part)) {
				tableConstraints.push(part.trim());
				continue;
			}
			const def = splitColDef(part);
			if (def) defs.set(def.name.toLowerCase(), part.trim());
		}
		const fks = [];
		for (const [col, part] of defs) {
			const m = part.match(FK_RE);
			if (m) fks.push({ col, table: m[1].toLowerCase(), targetCol: (m[2] || '').toLowerCase() || null });
		}
		for (const part of tableConstraints) {
			const m = part.match(FK_RE);
			if (m) fks.push({ col: null, table: m[1].toLowerCase(), targetCol: null });
		}
		return {
			name: r.name.toLowerCase(),
			cols: db
				.prepare(`PRAGMA table_info("${r.name}")`)
				.all()
				.map((c) => c.name.toLowerCase()),
			defs,
			tableConstraints,
			fks,
		};
	});
	const indexes = db
		.prepare("SELECT name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY rowid")
		.all()
		.map((r) => ({ name: r.name.toLowerCase(), sql: r.sql.trim().replace(/;$/, '') }));
	try {
		db.close();
	} catch {
		/* ignore */
	}
	return { tables, indexes };
}

/* ---------------------------------------------------------------------- PG */

function readBaseline() {
	const raw = readFileSync(PG_PATH, 'utf8');
	const bi = raw.indexOf(BEGIN_MARK);
	const ei = raw.indexOf(END_MARK);
	const base = bi !== -1 && ei !== -1 && ei > bi ? raw.slice(0, bi) : raw;
	return { raw, base, hadSection: bi !== -1 && ei !== -1 && ei > bi };
}

/* --------------------------------------------------------------- type rules */

function baseType(name, rawType) {
	const t = String(rawType || '')
		.toUpperCase()
		.replace(/\s*\(.*\)$/, '')
		.trim();
	if (AT_NAME_RE.test(name)) return 'TIMESTAMPTZ';
	if (DATE_NAME_RE.test(name) || DATE_EXPLICIT.has(name)) return 'DATE';
	if (FLAG_RE.test(name) && ['INTEGER', 'INT', 'BOOLEAN', 'TINYINT', 'SMALLINT'].includes(t)) return 'BOOLEAN';
	if (['INTEGER', 'INT', 'BIGINT', 'MEDIUMINT', 'SMALLINT', 'TINYINT'].includes(t)) return 'BIGINT';
	if (['REAL', 'FLOAT', 'DOUBLE', 'NUMERIC', 'DECIMAL'].includes(t)) return 'NUMERIC(18,6)';
	return 'TEXT';
}

function transformDefault(raw, type) {
	if (/^\(?\s*datetime\s*\(/i.test(raw) || /^CURRENT_TIMESTAMP$/i.test(raw)) {
		return type === 'TIMESTAMPTZ' ? 'now()' : "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";
	}
	if (/^\(?\s*date\s*\(/i.test(raw)) {
		return type === 'DATE'
			? "(now() AT TIME ZONE 'UTC')::date"
			: "to_char((now() AT TIME ZONE 'UTC')::date, 'YYYY-MM-DD')";
	}
	if (type === 'BOOLEAN') {
		if (raw === '1' || raw === '(1)') return 'TRUE';
		if (raw === '0' || raw === '(0)') return 'FALSE';
	}
	if ((type === 'DATE' || type === 'TIMESTAMPTZ') && (raw === "''" || raw === '""')) return null;
	return raw;
}

/* --------------------------------------------------------------------- plan */

const lite = await readSqliteSchema();
const { base: pgBase, hadSection } = readBaseline();
const pgPre = parsePgObjects(pgBase); // baseline WITHOUT the generated section
const liteByName = new Map(lite.tables.map((t) => [t.name, t]));

const batchTables = lite.tables.filter(
	(t) => !IGNORED_TABLES.has(t.name) && !isFtsTable(t.name) && !pgPre.tables.has(t.name),
);
const batchNames = new Set(batchTables.map((t) => t.name));

const missingColumns = [];
for (const t of lite.tables) {
	if (IGNORED_TABLES.has(t.name) || isFtsTable(t.name)) continue;
	const pgCols = pgPre.tables.get(t.name);
	if (!pgCols) continue; // whole table is generated as a CREATE
	for (const col of t.cols) if (!pgCols.has(col)) missingColumns.push({ table: t.name, col });
}
const missingColumnKeys = new Set(missingColumns.map((c) => `${c.table}.${c.col}`));

const missingIndexes = lite.indexes.filter((i) => !pgPre.indexes.has(i.name));

/* ---------------------------------------------------- FK-aware type resolve */

const typeMemo = new Map();
const inProgress = new Set();

function primaryKeyOf(table) {
	const t = liteByName.get(table);
	if (t) {
		for (const [col, part] of t.defs) if (/\bPRIMARY KEY\b/i.test(part)) return col;
		for (const c of t.tableConstraints) {
			const m = c.match(/^PRIMARY KEY\s*\(\s*([a-z_][a-z0-9_]*)/i);
			if (m) return m[1].toLowerCase();
		}
	}
	return 'id';
}

function columnType(table, col) {
	const key = `${table}.${col}`;
	if (typeMemo.has(key)) return typeMemo.get(key);
	const pgCols = pgPre.tables.get(table);
	if (pgCols?.has(col)) {
		const t = pgCols.get(col) || 'TEXT';
		typeMemo.set(key, t);
		return t;
	}
	const liteT = liteByName.get(table);
	if (!liteT) fail(`FK target ${key} is not a table in either schema`);
	const part = liteT.defs.get(col);
	if (!part) fail(`FK target ${key} is not a column in either schema`);
	if (inProgress.has(key)) {
		const t = baseType(col, splitColDef(part).type);
		typeMemo.set(key, t);
		return t;
	}
	inProgress.add(key);
	const def = splitColDef(part);
	const fk = part.match(FK_RE);
	const type = fk
		? columnType(fk[1].toLowerCase(), (fk[2] || primaryKeyOf(fk[1].toLowerCase())).toLowerCase())
		: baseType(def.name, def.type);
	inProgress.delete(key);
	typeMemo.set(key, type);
	return type;
}

/* --------------------------------------------------------------- emission */

function emitColumn(part) {
	const def = splitColDef(part);
	if (!def) fail(`cannot parse column definition: ${part}`);
	const fk = part.match(FK_RE);
	const type = fk
		? columnType(fk[1].toLowerCase(), (fk[2] || primaryKeyOf(fk[1].toLowerCase())).toLowerCase())
		: baseType(def.name, def.type);
	let toks = def.restTokens.slice();
	const di = toks.findIndex((t) => /^DEFAULT$/i.test(t));
	let dropped = false;
	if (di !== -1 && di + 1 < toks.length) {
		const next = transformDefault(toks[di + 1], type);
		if (next === null) {
			toks.splice(di, 2);
			dropped = true;
		} else toks[di + 1] = next;
	}
	toks = toks.filter((t) => !/^AUTOINCREMENT$/i.test(t));
	if (dropped) {
		const ni = toks.findIndex((t) => /^NOT$/i.test(t));
		if (ni !== -1 && /^NULL$/i.test(toks[ni + 1] || '')) toks.splice(ni, 2);
	}
	const rest = toks.join(' ').trim();
	return `${def.name} ${type}${rest ? ` ${rest}` : ''}`;
}

function emitCreateTable(t) {
	const lines = [];
	for (const col of t.cols) {
		const part = t.defs.get(col);
		if (!part) fail(`table ${t.name}: column ${col} has no definition in sqlite_master`);
		lines.push(`  ${emitColumn(part)}`);
	}
	for (const c of t.tableConstraints) lines.push(`  ${c}`);
	return `CREATE TABLE IF NOT EXISTS ${t.name} (\n${lines.join(',\n')}\n);`;
}

function emitAlter({ table, col }) {
	const t = liteByName.get(table);
	const part = t?.defs.get(col);
	if (!part) fail(`ALTER target ${table}.${col} has no definition in sqlite_master`);
	return `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${emitColumn(part)};`;
}

function emitIndex({ name, sql }) {
	const open = sql.indexOf('(');
	if (open === -1) fail(`index ${name}: no column list in ${sql}`);
	const close = matchParen(sql, open);
	if (close === -1) fail(`index ${name}: unbalanced parens in ${sql}`);
	const head = sql.slice(0, open);
	const cols = sql.slice(open, close + 1);
	const where = sql.slice(close + 1).trim();
	const m = head.match(
		/^CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF NOT EXISTS\s+)?([a-z_][a-z0-9_]*)\s+ON\s+([a-z_][a-z0-9_]*)\s*$/i,
	);
	if (!m) fail(`index ${name}: cannot parse header ${head}`);
	return `CREATE ${m[1] || ''}INDEX IF NOT EXISTS ${m[2]} ON ${m[3]} ${cols}${where ? ` ${where}` : ''};`;
}

/* ------------------------------------------------------------- ordering */

function topo(nodes, depsOf) {
	const keys = new Set(nodes.map((n) => n.key));
	const done = new Set();
	const out = [];
	const pending = [...nodes];
	while (pending.length) {
		let progressed = false;
		for (let i = 0; i < pending.length; i++) {
			const n = pending[i];
			const blocked = [...depsOf(n)].some((d) => keys.has(d) && !done.has(d));
			if (!blocked) {
				out.push(n);
				done.add(n.key);
				pending.splice(i, 1);
				i--;
				progressed = true;
			}
		}
		if (!progressed) {
			warn(`dependency cycle among: ${pending.map((n) => n.key).join(', ')} — emitting in source order`);
			out.push(...pending);
			break;
		}
	}
	return out;
}

// A CREATE's FK must target a column that exists by the time it runs:
// either the baseline already has it, or an earlier CREATE in this batch
// creates it. An ALTER that would add the target runs AFTER every CREATE —
// that ordering can never be satisfied, so it is an error, not a warning.
for (const t of batchTables) {
	for (const fk of t.fks) {
		if (batchNames.has(fk.table)) continue;
		const targetCol = fk.targetCol || primaryKeyOf(fk.table);
		if (!pgPre.tables.get(fk.table)?.has(targetCol)) {
			fail(
				`${t.name} references ${fk.table}(${targetCol}), which the baseline lacks — ` +
					'the column would be added by an ALTER that runs after this CREATE. ' +
					'Add the column to the hand-written baseline (or fix the FK) and re-run.',
			);
		}
	}
}

const createNodes = topo(
	batchTables.map((t) => ({ key: t.name, t })),
	// Self-FKs are inline in their own CREATE (SQLite allows them, PG does too) — never a dep.
	(n) => n.t.fks.filter((f) => f.col !== null && f.table !== n.t.name && batchNames.has(f.table)).map((f) => f.table),
);

const alterNodes = topo(
	missingColumns.map((c) => ({ key: `${c.table}.${c.col}`, ...c })),
	(n) => {
		const t = liteByName.get(n.table);
		const part = t?.defs.get(n.col) || '';
		const fk = part.match(FK_RE);
		if (!fk) return [];
		const targetTable = fk[1].toLowerCase();
		if (batchNames.has(targetTable) || pgPre.tables.get(targetTable)?.has((fk[2] || '').toLowerCase())) return [];
		const targetCol = (fk[2] || primaryKeyOf(targetTable)).toLowerCase();
		return missingColumnKeys.has(`${targetTable}.${targetCol}`) ? [`${targetTable}.${targetCol}`] : [];
	},
);

// ALTER FK targets: batch tables are created first (phase 1) — fine. Any
// other target column must already be in the baseline or in this ALTER set.
for (const n of alterNodes) {
	const t = liteByName.get(n.table);
	const part = t?.defs.get(n.col) || '';
	const fk = part.match(FK_RE);
	if (!fk) continue;
	const targetTable = fk[1].toLowerCase();
	if (batchNames.has(targetTable)) continue;
	const targetCol = (fk[2] || primaryKeyOf(targetTable)).toLowerCase();
	if (pgPre.tables.get(targetTable)?.has(targetCol)) continue;
	if (missingColumnKeys.has(`${targetTable}.${targetCol}`)) continue;
	fail(`ALTER ${n.table}.${n.col} references ${targetTable}(${targetCol}), which exists in neither schema`);
}

/* ----------------------------------------------------------- assemble body */

const body = [];
body.push('-- Tables, columns and indexes the SQLite schema has that the hand-written');
body.push('-- baseline above lacks. Regenerate: npm run parity:sync · Verify: npm run parity.');
body.push('BEGIN;');
body.push('');
body.push(`-- (1) ${createNodes.length} missing tables, FK-target order.`);
for (const n of createNodes) body.push(emitCreateTable(n.t), '');
body.push(`-- (2) ${alterNodes.length} missing columns on baseline tables.`);
for (const n of alterNodes) body.push(emitAlter(n), '');
body.push(`-- (3) ${missingIndexes.length} missing indexes.`);
for (const idx of missingIndexes) body.push(emitIndex(idx));
body.push('');
body.push('COMMIT;');
const section = `${BEGIN_MARK}\n${body.join('\n')}\n${END_MARK}\n`;

const trimmedBase = pgBase.replace(/\s+$/, '');
const out = hadSection ? `${trimmedBase}\n${section}` : `${trimmedBase}\n\n${section}`;
writeFileSync(PG_PATH, out, 'utf8');

console.log(
	JSON.stringify(
		{
			ok: true,
			hadSection,
			generated: { tables: createNodes.length, columns: alterNodes.length, indexes: missingIndexes.length },
			file: relative(SERVER, PG_PATH).replaceAll('\\', '/'),
			next: 'npm run parity',
		},
		null,
		2,
	),
);
